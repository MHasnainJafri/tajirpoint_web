// Pure helpers behind scripts/media.mjs — kept separate so the vitest suite can
// import them and check the committed manifest and READMEs are up to date.
//
// Nothing here touches the network. The manifest is a sorted list of every file
// under public/media, so <MediaSlot> can decide at BUILD time which slots have
// a real file and never asks the browser for one that does not exist.

import fs from "node:fs";
import path from "node:path";

export const VIDEO_EXT = [".mp4", ".webm"];
export const IMAGE_EXT = [".webp", ".avif", ".jpg", ".jpeg", ".png"];

/** Recursively lists files under `dir`, as POSIX paths relative to `dir`. */
export function listFiles(dir) {
  const out = [];
  const walk = (abs, rel) => {
    let entries = [];
    try {
      entries = fs.readdirSync(abs, { withFileTypes: true });
    } catch {
      return;
    }
    for (const e of entries) {
      if (e.name.startsWith(".")) continue;
      const nextAbs = path.join(abs, e.name);
      const nextRel = rel ? `${rel}/${e.name}` : e.name;
      if (e.isDirectory()) walk(nextAbs, nextRel);
      else out.push(nextRel);
    }
  };
  walk(dir, "");
  return out.sort();
}

/** Only real media files go in the manifest (READMEs and stray files do not). */
export function buildManifest(files) {
  const media = files.filter((f) => {
    const ext = path.extname(f).toLowerCase();
    return VIDEO_EXT.includes(ext) || IMAGE_EXT.includes(ext);
  });
  return { files: media };
}

const RATIO_DEFAULT = { video: "16:10", image: "16:10", phone: "4:5" };

function ratioOf(media) {
  return media.ratio ? media.ratio.replace("/", ":") : RATIO_DEFAULT[media.expect];
}

function expectedFiles(media) {
  const s = media.slot;
  if (media.expect === "video") {
    return `\`${s}.mp4\` (+ \`${s}-poster.jpg\`), or an image \`${s}.webp\` / \`${s}.jpg\``;
  }
  if (media.expect === "phone") {
    return `\`${s}.webp\` / \`${s}.jpg\` / \`${s}.png\` (portrait), or \`${s}.mp4\` (+ \`${s}-poster.jpg\`)`;
  }
  return `\`${s}.webp\` / \`${s}.jpg\` / \`${s}.png\`, or \`${s}.mp4\` (+ \`${s}-poster.jpg\`)`;
}

function sizeOf(media) {
  if (media.expect === "phone") return "1080 × 1350";
  return "1600 × 1000 image · 1920 × 1200 (or 1080p) video";
}

/** Which kind of file currently fills a slot, or "—". */
export function slotStatus(files, business, media) {
  const base = `business/${business}/${media.slot}`;
  const has = (ext) => files.includes(`${base}${ext}`);
  if (VIDEO_EXT.some(has)) return "video ✓";
  if (media.youtube) return "YouTube ✓";
  if (media.vimeo) return "Vimeo ✓";
  if (IMAGE_EXT.some(has)) return "image ✓";
  return "—";
}

/** README.md for public/media/business/<slug>/. */
export function renderBusinessReadme(business) {
  const slots = [
    { section: "Hero (top of the page)", media: business.hero.media },
    ...business.features.map((f) => ({ section: f.title, media: f.media })),
  ];
  const rows = slots
    .map(
      ({ section, media }) =>
        `| ${section} | \`${media.slot}\` | ${media.expect} | ${expectedFiles(media)} | ${ratioOf(media)} · ${sizeOf(media)} | ${media.alt} |`
    )
    .join("\n");

  return `# Media for /business/${business.slug} — ${business.name}

Drop files into this folder using the exact names below, then rebuild/redeploy.
Until a file exists the page shows a branded placeholder, so nothing breaks.
See ../../README.md for formats, sizes and compression tips.

| Section | Slot | Best as | File name(s) | Ratio · size | What it should show |
|---|---|---|---|---|---|
${rows}

Order of preference for a slot: local video (\`.mp4\`/\`.webm\`) → YouTube/Vimeo id
set in \`src/lib/marketing/businesses.ts\` → local image → placeholder.

_This file is generated by \`pnpm media:docs\` from the business catalog._
`;
}

/** The top-level MEDIA-CHECKLIST.md. */
export function renderChecklist(businesses, files) {
  let total = 0;
  let filled = 0;
  const sections = businesses
    .map((b) => {
      const slots = [
        { section: "Hero", media: b.hero.media },
        ...b.features.map((f) => ({ section: f.title, media: f.media })),
      ];
      const rows = slots
        .map(({ section, media }) => {
          total += 1;
          const status = slotStatus(files, b.slug, media);
          if (status !== "—") filled += 1;
          return `| ${status === "—" ? "[ ]" : "[x]"} | ${section} | \`public/media/business/${b.slug}/${media.slot}.*\` | ${media.expect} | ${ratioOf(media)} | ${status} |`;
        })
        .join("\n");
      return `## ${b.name} — /business/${b.slug} (${slots.length} slots)

| Done | Section | Path | Best as | Ratio | Current |
|---|---|---|---|---|---|
${rows}
`;
    })
    .join("\n");

  return `# Media checklist — marketing site

Every image/video slot on the business pages. ${filled} of ${total} slots filled.

How to add media: read \`public/media/README.md\`. In short — name the file after
the slot, put it in the folder shown, run \`pnpm media:docs\` (optional, refreshes
this list) and redeploy. Videos: MP4 (H.264), muted, 10–30 s, under ~8 MB, plus a
\`<slot>-poster.jpg\`. Images: WebP or JPG, sRGB.

Other slots on the site (not part of this list):
- Home page photos in \`public/images/\` — see \`IMAGE-PROMPTS.md\`.

${sections}
_Generated by \`pnpm media:docs\` from \`src/lib/marketing/businesses.ts\`._
`;
}
